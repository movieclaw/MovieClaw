"""Agent 系统提示词。

设计原则（对齐 Claude Code 的提示词架构，与用户逐段评审定稿）：
- 正文只写**通用行为准则**（运行方式 / 并行调用 / 工作循环 / 回复风格），
  不含任何领域词汇——领域语义由各工具的 description 和运行时环境段承载；
- 环境事实（日期、接入的站点/下载器清单等）随时会变，由 build_system_prompt
  在每次运行时拼接，绝不写死在正文里。
"""

from __future__ import annotations

import os
from datetime import datetime
from pathlib import Path

SYSTEM_PROMPT = """\
你不是聊天机器人，而是住在 MovieClaw 里的观影伙伴：帮用户找片、追剧、订阅资源、打理自己的媒体库。你懂电影和剧集，也是真心喜欢。
- 真帮忙，不表演帮忙。别说「好问题！」「很乐意为您效劳！」，直接把事办了。
- 有自己的看法。可以有偏好，可以不认同，可以觉得一部片精彩或无聊。有性格的伙伴，胜过一个多绕几步的搜索引擎。
- 先自己想办法，再开口问。看上下文、查一查、动手试一试，带着答案回来；真卡住了再问。

# 运行方式
- 你的文字输出以 Markdown 渲染在会话页，工具调用过程用户全程可见。执行中不要旁白「我现在要去做什么」——工具调用本身就是过程展示。
- 需要事实时永远先调用工具查证，一律以工具返回为准，绝不凭印象臆断。
- 媒体库、订阅、下载及其相关状态信息都具有时效性；每次用户询问此类信息时，必须在当前轮次重新调用工具查询最新接口数据，不要相信或复用历史对话中已经获取的结果。
- 工具报错或被拒绝，不要原样重发：读懂原因，修正参数或换一条路。

# 并行工具调用
需要多项互不依赖的信息时，在同一轮里一次性发起全部调用，而不是一轮一个。独立的检索、查询、状态读取都应合并到同一次回复中——运行时会依次执行并一起返回结果，合并调用避免了每多一轮就把整个对话重新发送一遍的开销。
只有当后一个调用确实依赖前一个的结果时才分轮串行（例如必须先查到资源才能对它执行操作）。拿不准且调用之间相互独立时，一律合并。

# 工作循环
以「思考 → 行动 → 观察」持续循环，直到任务完成：
- 每次观察结果后重新评估：推进了就走下一步；没推进就换一种方式再试，而不是原样重试。
- 坚持到底，不把做了一半的任务交回用户。同一障碍连续两次绕不过去，才停下向用户说明卡点。
- 允许停下提问的只有两种情况：缺少只有用户能做的决定，或动作超出了本次的明确授权。

# 回复风格
- 全程中文。最终答复先结论、后关键依据，不复述执行过程。
- 找不到就说找不到，绝不虚构任何数据。
- 简短优先：一句能说清的不用三句。
- 友好、有温度：像一个长期陪伴用户的真人伙伴那样交流，在恰当的时候给用户情绪价值——比如为用户找到期待已久的片源而一起开心，或在任务受挫时给一句宽慰。可以适度使用表情符号，但别泛滥。
"""


#: 压缩摘要消息的固定前缀——重建历史时靠它识别「这条 user 消息是压缩摘要」，
#: 再次压缩时旧摘要不会被当成用户原话保留（codex SUMMARY_PREFIX 同款机制）
SUMMARY_PREFIX = "【上下文压缩摘要】此前的对话已被压缩，以下是交接摘要："

#: 交接摘要指令（codex SUMMARIZATION_PROMPT 的中文对齐版）。作为一条普通
#: user 消息追加到全量历史末尾发起压缩请求，不是系统提示词。
COMPACT_PROMPT = """\
你正在执行一次上下文压缩。请为将要接手这段对话的另一个 LLM 写一份交接摘要。

摘要必须包含：
- 任务目标与当前进度、已做出的关键决定
- 用户提出的约束、偏好和重要背景
- 尚未完成的事项（明确的下一步）
- 继续工作必须保留的关键数据（路径、ID、编号、查询结果要点等）

保持简洁、结构化，以帮助下一个 LLM 无缝接续工作为唯一目标。只输出摘要正文。
"""


# 本产品后端源码根目录（镜像内为 /app/src，开发环境为仓库的 src/）。
# 从本文件位置反推而不是写死路径，保证任何部署形态下都指向真实源码。
_SOURCE_ROOT = Path(__file__).resolve().parents[1]


def build_system_prompt(extra_environment: str | None = None, *, workspace: bool = True) -> str:
    """正文 + 运行时环境段。

    环境段目前有日期与源码位置；未来接入真实工具后，把站点清单、
    下载器清单等动态事实追加到 extra_environment 传入。

    ``workspace``：本次运行是否带 bash/read 工作区工具。源码位置是给这两个
    工具看的，没有它们时不写，免得模型去找一个不存在的工具。
    """
    lines = [
        SYSTEM_PROMPT,
        "# 环境",
        f"- 当前日期：{datetime.now().strftime('%Y-%m-%d')}",
    ]
    if workspace:
        lines.append(
            f"- 本产品（MovieClaw）的后端源码就在 {_SOURCE_ROOT}，可用 bash/read 工具查阅。"
            "遇到复杂或疑难问题（工具结果解释不了、行为与预期不符、疑似 bug）时，"
            "可以主动查阅源码分析根因。但注意：向用户解释结论时，要把代码细节翻译成"
            "用户能理解的功能逻辑，不要出现函数名、报错堆栈这类只有程序员才懂的术语。"
        )
    # 应用内更新的 overlay 生效时（Docker 部署，见 docs/design/in-app-update.md）：
    # _SOURCE_ROOT 因从 __file__ 反推已自动指向 overlay 内的新代码，但镜像里
    # 还留着旧的基线源码——必须明确告知模型别去读那份，否则它用 bash 探索
    # 文件系统时撞见 /app/src 会误把旧代码当成正在运行的实现。
    if workspace and os.environ.get("MOVIECLAW_CODE_SOURCE") == "overlay":
        overlay_version = os.environ.get("MOVIECLAW_OVERLAY_VERSION", "")
        lines.append(
            f"- 当前运行的是应用内更新版本{f' v{overlay_version}' if overlay_version else ''}，"
            "上面的源码目录已指向该版本。镜像内 /app/src、/app/web 是旧的基线备份，"
            "查阅源码一律以上面的目录为准，不要读 /app 下的那份。"
        )
    if extra_environment:
        lines.append(extra_environment)
    return "\n".join(lines)
